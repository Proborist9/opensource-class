#.split() --- breaks the string into a list of words, and .join() joins the list of words into a string.
#.replace() --- replaces a word in a string with another word.
#.strip() --- removes any leading or trailing whitespace from a string.
#.join() --- joins a list of strings into a single string, with a specified separator.
#.replace() --- replaces a specified substring with another substring in a string.
#lower() --- converts all characters in a string to lowercase.
#upper() --- converts all characters in a string to uppercase.